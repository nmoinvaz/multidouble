"""The constants of src/explog.rs, derived in exact integer and rational arithmetic, and their Rust source.

ln 2 comes from the series ln 2 = sum_{j >= 1} 1 / (j 2^j) in fixed point with P fractional bits: each term floored,
so the sum S satisfies S <= ln 2 2^P < S + P + 1 + 2^P tail, with the tail after P terms below 2^-P. The parts of a
value known only to such an interval are taken where both ends round to the same parts, which is checked. ln 2 is
also checked against Python's decimal module (libmpdec, a separate implementation) to 1000 digits. The factorials'
reciprocals and 1/3 are exact rationals.

  LN2_HI      ln 2 rounded to 42 significant bits, so that k LN2_HI is exact for every integer |k| < 2^11
  LN2_LO      ln 2 - LN2_HI, greedy eight parts (x_0 = RN(v), x_1 = RN(v - x_0), ...)
  LN2_DD      ln 2, greedy two parts (the logarithm's start at the top of the range)
  INV_FACT    1/j! for j = 0..=JMAX, greedy eight parts
  THIRD       1/3, greedy eight parts

A greedy expansion's first n parts are the greedy n-part expansion, so the double-double and quad-double code takes
the first two and four parts. usage: python3 scripts/explog_constants.py [check FILE [control]]; `check` exits
non-zero when the generated block of FILE (src/explog.rs) differs from the source derived here, compared with all
whitespace removed but the line break that ends each line comment, so that a changed value, sign, operator, type or
comment fails, and so does a declaration joined to the comment above it. `control` requires the untouched file to pass,
then makes two changes inside the generated block, one at a time, LN2_HI negated and LN2_HI's declaration joined to
its doc comment, matched with the whitespace the check ignores, and exits non-zero unless the check fails on each."""
import re
import struct
import sys
from decimal import Decimal, getcontext
from fractions import Fraction as Fr

P = 3400  # fractional bits of the ln 2 fixed point
JMAX = 43  # the largest factorial
PARTS = 8


def ln2_interval(p=P):
    """(lo, hi) with lo <= ln 2 <= hi, both rationals with denominator 2^p"""
    s = 0
    for j in range(1, p + 1):
        s += (1 << (p - j)) // j  # floor(2^(p - j) / j), each below the exact term by less than 1
    # sum_{j > p} 1 / (j 2^j) < 2^-p / (p + 1) < 2^-p, so the true value lies in [s, s + p + 1] units of 2^-p
    return Fr(s, 1 << p), Fr(s + p + 1, 1 << p)


def rn(x):
    """x rounded to the nearest binary64, ties to even (int / int true division is correctly rounded)"""
    return float(x) if x == 0 else x.numerator / x.denominator


def rn_bits(x, bits):
    """x > 0 rounded to `bits` significant bits, ties to even"""
    e = x.numerator.bit_length() - x.denominator.bit_length()
    # 2^e <= x < 2^(e + 2); scale so that the integer part has `bits` or `bits` + 1 bits
    sh = bits - 1 - e
    while True:
        q = x * Fr(2) ** sh
        if q < 2 ** (bits - 1):
            sh += 1
        elif q >= 2 ** bits:
            sh -= 1
        else:
            break
    f = q.numerator // q.denominator
    rem = q - f
    if rem > Fr(1, 2) or (rem == Fr(1, 2) and f % 2 == 1):
        f += 1
    return Fr(f) / Fr(2) ** sh


def greedy(v, n=PARTS):
    """the greedy n-part expansion of the exact rational v"""
    out = []
    for _ in range(n):
        c = rn(v)
        out.append(c)
        v -= Fr(c)
    return out


def greedy_interval(lo, hi, n=PARTS):
    """the greedy n-part expansion of every value in [lo, hi]; fails if the ends' expansions differ"""
    a, b = greedy(lo, n), greedy(hi, n)
    assert a == b, f'the interval is too wide for {n} parts: {a} != {b}'
    return a


def hexf(x):
    return '0x%016x' % struct.unpack('<Q', struct.pack('<d', x))[0]


def constants():
    lo, hi = ln2_interval()
    # an independent check: libmpdec's ln 2 to 1000 digits lies in the interval, widened by its last digit
    getcontext().prec = 1010
    d = Decimal(2).ln()
    dl = Fr(d) - Fr(1, 10 ** 1005)
    dh = Fr(d) + Fr(1, 10 ** 1005)
    assert dl <= hi and lo <= dh, 'ln 2 disagrees with the decimal module'
    hi42 = rn_bits(lo, 42)
    assert hi42 == rn_bits(hi, 42), 'ln 2 rounds to two 42-bit values'
    # k LN2_HI exact for |k| < 2^11: a 42-bit significand times an 11-bit integer has at most 53 bits
    num = hi42 * Fr(2) ** 42
    assert num.denominator == 1 and num.numerator < 2 ** 42
    lo_parts = greedy_interval(lo - hi42, hi - hi42)
    dd = greedy_interval(lo, hi, 2)
    fact = [greedy(Fr(1, _fact(j))) for j in range(JMAX + 1)]
    third = greedy(Fr(1, 3))
    return dict(ln2=(lo, hi), hi=float(hi42), lo=lo_parts, dd=dd, fact=fact, third=third)


def _fact(j):
    f = 1
    for i in range(2, j + 1):
        f *= i
    return f


def rust(c):
    """the constants as Rust source, in rustfmt's layout"""
    def arr(v, ind):
        pad = ' ' * (ind + 4)
        return '[\n' + ''.join(f'{pad}f64::from_bits({hexf(x)}),\n' for x in v) + ' ' * ind + ']'

    lines = ['// generated by scripts/explog_constants.py, do not edit',
             '/// ln 2 rounded to 42 significant bits: k LN2_HI is exact for every integer |k| < 2^11',
             f'const LN2_HI: f64 = f64::from_bits({hexf(c["hi"])});',
             '/// ln 2 - LN2_HI, greedy eight parts',
             f'const LN2_LO: [f64; 8] = {arr(c["lo"], 0)};',
             '/// ln 2, greedy two parts',
             # rustfmt keeps a two-element array on one line
             'const LN2_DD: [f64; 2] = [' + ', '.join(f'f64::from_bits({hexf(x)})' for x in c['dd']) + '];',
             f'/// 1/j! for j = 0..={JMAX}, greedy eight parts',
             f'const INV_FACT: [[f64; 8]; {JMAX + 1}] = [']
    lines += [f'    {arr(v, 4)},' for v in c['fact']]
    lines += ['];', '/// 1/3, greedy eight parts', f'const THIRD: [f64; 8] = {arr(c["third"], 0)};',
              '// end of generated constants']
    return '\n'.join(lines)


BLOCK = re.compile(r'// generated by scripts/explog_constants\.py.*?// end of generated constants', re.S)
# LN2_HI's declaration with any whitespace the check ignores, and the line break before it
DECL = re.compile(r'(const\s*LN2_HI\s*:\s*f64\s*=\s*)(f64\s*::\s*from_bits\s*\()')
JOIN = re.compile(r'\n(\s*const\s*LN2_HI\s*:)')


def block(text):
    """the generated block of a source text with its whitespace removed but each line comment's closing line break,
    or None"""
    m = BLOCK.search(text)
    if not m:
        return None
    lines = [re.sub(r'\s+', '', x) for x in m.group(0).split('\n')]
    return ''.join(x + '\n' if '//' in x else x for x in lines)


def mutate(text, pat, rep):
    """text with pat's first match inside the generated block replaced by rep"""
    m = BLOCK.search(text)
    return text if not m else text[:m.start()] + pat.sub(rep, m.group(0), 1) + text[m.end():]


if __name__ == '__main__':
    c = constants()
    src = rust(c)
    if len(sys.argv) > 2 and sys.argv[1] == 'check':
        text = open(sys.argv[2]).read()
        same = block(text) is not None and block(text) == block(src)
        if len(sys.argv) > 3 and sys.argv[3] == 'control':
            # the untouched file must pass, and each change must land inside its generated block and then fail
            ok = same
            for name, pat, rep in (('LN2_HI negated', DECL, r'\1-\2'), ('LN2_HI joined to its comment', JOIN, r' \1')):
                bad = mutate(text, pat, rep)
                moved = block(bad) is not None and block(bad) != block(text)
                caught = moved and block(bad) != block(src)
                ok &= caught
                print(f'control, {name}:', 'caught' if same and caught else 'NOT caught' if same else
                      'not run: the untouched file fails the check')
            sys.exit(0 if ok else 1)
        if not same:
            print('the generated block of', sys.argv[2], 'differs from the derived source')
            sys.exit(1)
        print('PASS: the generated block of', sys.argv[2], 'is the derived source')
    else:
        print(src)
